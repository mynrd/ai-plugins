"""Generate native Codex agents from the canonical Claude specialist profiles.

Python 3.11+, no dependencies. Run with --check in validation.
"""

import argparse
import json
import re
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLUGIN = ROOT / "plugins" / "mynrd-flow"


def expected_agents():
    preamble = (PLUGIN / "adapters" / "codex-worker.md").read_text(encoding="utf-8").strip()
    result = {}
    for source in sorted((PLUGIN / "agents").glob("mynrd-*.md")):
        _, metadata, body = source.read_text(encoding="utf-8").split("---", 2)
        name = re.search(r"^name: (.+)$", metadata, re.M).group(1)
        description = re.search(r"^description: (.+)$", metadata, re.M).group(1)
        # Claude's shell allowlist restriction does not apply to Codex tools.
        body, count = re.subn(
            r"^- \*\*Plain shell commands only[^\n]+",
            "- **Use the session's available tools.** Prefer file search/read tools or shell reads, and apply_patch for edits. Follow the host shell syntax and the session's approval rules.",
            body, flags=re.M,
        )
        assert count == 1, f"Expected one Claude shell rule in {source}"
        instructions = preamble + "\n\n" + body.strip() + "\n"
        instructions = re.sub(r"/mynrd-([a-z-]+)", r"$mynrd-\1", instructions)
        description = re.sub(r"/mynrd-([a-z-]+)", r"$mynrd-\1", description)
        # JSON strings are valid TOML basic strings; literal multiline strings keep prompts readable.
        assert "'''" not in instructions
        content = (
            "# Generated by scripts/generate_codex_agents.py; edit agents/*.md or adapters/codex-worker.md.\n"
            f"name = {json.dumps(name)}\n"
            f"description = {json.dumps(description, ensure_ascii=False)}\n"
            "developer_instructions = '''\n" + instructions + "'''\n"
        )
        parsed = tomllib.loads(content)
        assert parsed["name"] == source.stem
        result[source.stem + ".toml"] = content
    assert len(result) == 6
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = PLUGIN / "codex-agents"
    expected = expected_agents()
    if args.check:
        assert {p.name for p in destination.glob("*.toml")} == set(expected), "Codex agent coverage differs"
        for name, content in expected.items():
            assert (destination / name).read_text(encoding="utf-8") == content, f"Regenerate {name}"
    else:
        destination.mkdir(exist_ok=True)
        for name, content in expected.items():
            (destination / name).write_text(content, encoding="utf-8", newline="\n")
    print(f"{'Checked' if args.check else 'Generated'} {len(expected)} native Codex agents.")


if __name__ == "__main__":
    main()
